/**
 * Filigrane invisible watermark, version 1 ("fgw1").
 *
 * A 64-bit codeword (magic · version · flags · 32-bit id · CRC-16) is spread over
 * mid-low frequency DCT coefficients of the luminance of a *canonical* copy of the
 * image (256 px on the long side). Working at a canonical scale makes the mark
 * survive resizing; spreading each bit over ~300 coefficients makes it survive
 * JPEG/WebP recompression and mild colour edits. Embedding is "informed": each
 * coefficient is only pushed as far as needed, weighted by local texture so the
 * change stays below visibility.
 *
 * Known limits of v1 (documented, on the roadmap): cropping, rotation and
 * flipping break the synchronisation.
 *
 * The technique is classic spread-spectrum DCT watermarking (1990s literature);
 * it is implemented here from scratch.
 */
import type { Raster } from '../image/raster.ts';
import { dct8, idct8, resizeArea, resizeBilinear } from './dsp.ts';

export const WATERMARK_ALG = 'io.filigrane.fgw1';

export interface WatermarkPayload {
  /** Content entirely generated by AI. */
  aiGenerated: boolean;
  /** Existing content partially modified by AI. */
  aiModified?: boolean;
  /** 32-bit identifier, e.g. derived from the C2PA manifest (see `payloadIdFrom`). */
  id: number;
}

export interface EmbedOptions {
  /** Watermark strength multiplier (default 1). Higher is more robust and more visible. */
  strength?: number;
  /** Secret or public key that seeds the spreading sequence (default: public Filigrane key). */
  key?: string;
}

export interface DetectResult {
  detected: boolean;
  payload?: WatermarkPayload;
  /** Mean normalised correlation of the 64 bits (0 = noise, ~1 = pristine). */
  confidence: number;
  /** Number of bits whose correlation is weak (useful for diagnostics). */
  weakBits: number;
}

const CANONICAL = 256;
const BITS = 64;
const MAGIC = 0xa5;
const VERSION = 1;
const DEFAULT_KEY = 'filigrane:fgw1:public';
/** DCT coefficients (u, v) carrying the mark: low/mid frequencies survive scaling and compression. */
const COEFS: readonly [number, number][] = [
  [0, 2],
  [2, 0],
  [1, 2],
  [2, 1],
  [1, 3],
  [3, 1],
];

// ---------------------------------------------------------------- codeword

function crc16(bits: number[]): number {
  let crc = 0xffff;
  for (const bit of bits) {
    const top = ((crc >> 15) & 1) ^ bit;
    crc = (crc << 1) & 0xffff;
    if (top) crc ^= 0x1021;
  }
  return crc;
}

function pushBits(out: number[], value: number, count: number): void {
  for (let i = count - 1; i >= 0; i--) out.push(Math.floor(value / 2 ** i) % 2);
}

function readBits(bits: number[], start: number, count: number): number {
  let v = 0;
  for (let i = 0; i < count; i++) v = v * 2 + bits[start + i];
  return v;
}

export function encodeCodeword(p: WatermarkPayload): number[] {
  const bits: number[] = [];
  pushBits(bits, MAGIC, 8);
  pushBits(bits, VERSION, 4);
  pushBits(bits, (p.aiGenerated ? 1 : 0) | (p.aiModified ? 2 : 0), 4);
  pushBits(bits, p.id >>> 0, 32);
  pushBits(bits, crc16(bits), 16);
  return bits;
}

export function decodeCodeword(bits: number[]): WatermarkPayload | undefined {
  if (readBits(bits, 0, 8) !== MAGIC || readBits(bits, 8, 4) !== VERSION) return undefined;
  if (crc16(bits.slice(0, 48)) !== readBits(bits, 48, 16)) return undefined;
  const flags = readBits(bits, 12, 4);
  return { aiGenerated: !!(flags & 1), aiModified: !!(flags & 2), id: readBits(bits, 16, 32) };
}

/** Derives a 32-bit payload id from any string (e.g. a C2PA instance ID). */
export function payloadIdFrom(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193);
  return h >>> 0;
}

// ---------------------------------------------------------------- geometry & PRNG

function canonicalSize(w: number, h: number): [number, number] {
  const s = CANONICAL / Math.max(w, h);
  const cw = Math.max(64, Math.round((w * s) / 8) * 8);
  const ch = Math.max(64, Math.round((h * s) / 8) * 8);
  return [cw, ch];
}

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

interface ChipMap {
  /** Bit carried by chip i. */
  bit: Uint8Array;
  /** Pseudo-random sign of chip i (+1/-1). */
  pn: Int8Array;
}

const chipCache = new Map<string, ChipMap>();

function chips(total: number, key: string): ChipMap {
  const cacheKey = `${key}:${total}`;
  const hit = chipCache.get(cacheKey);
  if (hit) return hit;
  const rand = mulberry32(payloadIdFrom(key) ^ total);
  const order = new Uint32Array(total);
  for (let i = 0; i < total; i++) order[i] = i;
  for (let i = total - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const t = order[i];
    order[i] = order[j];
    order[j] = t;
  }
  const bit = new Uint8Array(total);
  const pn = new Int8Array(total);
  for (let i = 0; i < total; i++) {
    bit[order[i]] = i % BITS;
    pn[i] = rand() < 0.5 ? -1 : 1;
  }
  const map = { bit, pn };
  if (chipCache.size > 16) chipCache.clear();
  chipCache.set(cacheKey, map);
  return map;
}

// ---------------------------------------------------------------- luminance

function luminance(r: Raster): Float32Array {
  const y = new Float32Array(r.width * r.height);
  const d = r.data;
  for (let i = 0, p = 0; i < y.length; i++, p += 4) y[i] = 0.299 * d[p] + 0.587 * d[p + 1] + 0.114 * d[p + 2];
  return y;
}

function canonicalLuma(r: Raster): { img: Float32Array; cw: number; ch: number } {
  const [cw, ch] = canonicalSize(r.width, r.height);
  return { img: resizeArea(luminance(r), r.width, r.height, cw, ch), cw, ch };
}

// ---------------------------------------------------------------- embed

const coef = new Float64Array(64);

function embedPass(r: Raster, word: number[], strength: number, key: string): void {
  const { img, cw, ch } = canonicalLuma(r);
  const bx = cw / 8;
  const by = ch / 8;
  const total = bx * by * COEFS.length;
  const map = chips(total, key);
  const marked = img.slice();

  for (let b = 0; b < bx * by; b++) {
    const x = (b % bx) * 8;
    const y = Math.floor(b / bx) * 8;
    dct8(img, cw, x, y, coef);
    let energy = 0;
    for (let i = 1; i < 64; i++) energy += coef[i] * coef[i];
    const texture = Math.sqrt(energy / 63);
    // Texture masking: flat blocks get a gentle mark, busy blocks hide a stronger one.
    const alpha = strength * Math.min(9, 2.2 + 0.18 * texture);
    for (let k = 0; k < COEFS.length; k++) {
      const chip = b * COEFS.length + k;
      const [u, v] = COEFS[k];
      const idx = v * 8 + u;
      const sign = map.pn[chip] * (word[map.bit[chip]] ? 1 : -1);
      const current = sign * coef[idx];
      if (current < alpha) coef[idx] += sign * Math.min(alpha - current, 3 * alpha);
    }
    idct8(coef, marked, cw, x, y);
  }

  // Residual at canonical scale → upsample → add to RGB (luma-only change).
  const residual = new Float32Array(cw * ch);
  for (let i = 0; i < residual.length; i++) residual[i] = marked[i] - img[i];
  const full = resizeBilinear(residual, cw, ch, r.width, r.height);
  const d = r.data;
  for (let i = 0, p = 0; i < full.length; i++, p += 4) {
    const delta = full[i];
    d[p] = clamp255(d[p] + delta);
    d[p + 1] = clamp255(d[p + 1] + delta);
    d[p + 2] = clamp255(d[p + 2] + delta);
  }
}

function clamp255(v: number): number {
  return v < 0 ? 0 : v > 255 ? 255 : Math.round(v);
}

/** Embeds the payload into a copy of the raster. Images smaller than 64×64 are returned unchanged. */
export function embedWatermark(r: Raster, payload: WatermarkPayload, o: EmbedOptions = {}): Raster {
  const out: Raster = { width: r.width, height: r.height, data: r.data.slice() };
  if (r.width < 64 || r.height < 64) return out;
  const word = encodeCodeword(payload);
  const key = o.key ?? DEFAULT_KEY;
  const strength = o.strength ?? 1;
  // Two passes: the second one re-reinforces coefficients weakened by resampling and clipping.
  embedPass(out, word, strength, key);
  embedPass(out, word, strength * 0.6, key);
  return out;
}

// ---------------------------------------------------------------- detect

export function detectWatermark(r: Raster, o: { key?: string } = {}): DetectResult {
  if (r.width < 32 || r.height < 32) return { detected: false, confidence: 0, weakBits: BITS };
  const { img, cw, ch } = canonicalLuma(r);
  const bx = cw / 8;
  const by = ch / 8;
  const total = bx * by * COEFS.length;
  const map = chips(total, o.key ?? DEFAULT_KEY);
  const sum = new Float64Array(BITS);
  const energy = new Float64Array(BITS);
  for (let b = 0; b < bx * by; b++) {
    dct8(img, cw, (b % bx) * 8, Math.floor(b / bx) * 8, coef);
    for (let k = 0; k < COEFS.length; k++) {
      const chip = b * COEFS.length + k;
      const [u, v] = COEFS[k];
      const c = coef[v * 8 + u];
      // Clip outliers (strong edges) so a few big coefficients cannot dominate a bit.
      const clipped = Math.max(-24, Math.min(24, c));
      sum[map.bit[chip]] += map.pn[chip] * clipped;
      energy[map.bit[chip]] += clipped * clipped;
    }
  }
  const bits: number[] = [];
  let corr = 0;
  let weakBits = 0;
  for (let i = 0; i < BITS; i++) {
    bits.push(sum[i] > 0 ? 1 : 0);
    const n = energy[i] > 0 ? Math.abs(sum[i]) / Math.sqrt(energy[i] * (total / BITS)) : 0;
    corr += n;
    if (n < 0.15) weakBits++;
  }
  const payload = decodeCodeword(bits);
  return { detected: !!payload, payload, confidence: Math.min(1, corr / BITS), weakBits };
}
