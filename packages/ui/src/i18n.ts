export const LANGUAGES = Object.keys(STRINGS);

/** Picks the best available language for a BCP 47 tag ("fr-BE" → "fr"), falling back to English. */
export function resolveLanguage(tag: string | null | undefined): string {
  const base = (tag ?? '').toLowerCase().split(/[-_]/)[0];
  return base in STRINGS ? base : 'en';
}

export function strings(tag?: string | null): Strings {
  return STRINGS[resolveLanguage(tag)];
}
