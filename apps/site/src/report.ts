import type { VerifyImageResult } from '@filigranejs/core';
import { t } from './i18n.ts';

function esc(s: unknown): string {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

const fr = () => document.documentElement.lang === 'fr';

const SOURCE: Record<string, [string, string]> = {
  trainedAlgorithmicMedia: ['Generated by AI', 'Généré par IA'],
  compositeWithTrainedAlgorithmicMedia: ['Partly modified by AI', 'Modifié en partie par IA'],
  algorithmicMedia: ['Algorithmic (non-AI)', 'Algorithmique (hors IA)'],
  digitalCapture: ['Camera capture', 'Capture d’appareil photo'],
};

function sourceLabel(uri?: string): string {
  const key = uri?.split('/').pop() ?? '';
  const pair = SOURCE[key];
  return pair ? pair[fr() ? 1 : 0] : esc(key);
}

const CHECKS: Record<string, [string, string]> = {
  'assertion.hashedURI.match': ['Assertion intact', 'Assertion intacte'],
  'assertion.hashedURI.mismatch': ['Assertion modified', 'Assertion modifiée'],
  'assertion.missing': ['Assertion missing', 'Assertion manquante'],
  'assertion.dataHash.match': ['File content matches the signed hash', 'Le contenu du fichier correspond à l’empreinte signée'],
  'assertion.dataHash.mismatch': ['The file was modified after signing', 'Le fichier a été modifié après la signature'],
  'claimSignature.validated': ['Manifest signature is valid', 'La signature du manifeste est valide'],
  'claimSignature.mismatch': ['Manifest signature does not match', 'La signature du manifeste ne correspond pas'],
  'claimSignature.insideValidity': ['Certificate valid at verification time', 'Certificat valide au moment de la vérification'],
  'signingCredential.expired': ['Certificate expired or not yet valid', 'Certificat expiré ou pas encore valide'],
  'signingCredential.invalid': ['Certificate does not meet the C2PA profile', 'Le certificat ne respecte pas le profil C2PA'],
  'signingCredential.trusted': ['Signer is on the trust list', 'Signataire présent sur la liste de confiance'],
  'signingCredential.untrusted': ['Signer is not on the trust list', 'Signataire absent de la liste de confiance'],
};

function checkLabel(code: string, message: string): string {
  const pair = CHECKS[code];
  if (!pair) return esc(message);
  const text = pair[fr() ? 1 : 0];
  return code.startsWith('assertion.hashedURI') ? `${text} : <code>${esc(message)}</code>`.replace(' :', fr() ? ' :' : ':') : text;
}

const ACTIONS: Record<string, [string, string]> = {
  'c2pa.created': ['Created', 'Création'],
  'c2pa.edited': ['Edited', 'Modification'],
  'c2pa.opened': ['Opened', 'Ouverture'],
};

function actionLabel(a: string): string {
  const pair = ACTIONS[a];
  return pair ? pair[fr() ? 1 : 0] : esc(a.replace('c2pa.', ''));
}

function date(d?: Date): string {
  return d ? new Date(d).toLocaleDateString(fr() ? 'fr-FR' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric' }) : '—';
}

export function renderReport(v: VerifyImageResult, previewUrl?: string): string {
  const verdictText =
    v.verdict === 'ai-generated'
      ? t('r.gen', 'AI-generated')
      : v.verdict === 'ai-modified'
        ? t('r.mod', 'Modified with AI')
        : t('r.none', 'No AI signal found');
  const verdictClass = v.tampered ? 'bad' : v.verdict === 'no-ai-signal' ? 'none' : 'ai';
  const sub =
    v.verdict === 'no-ai-signal'
      ? fr()
        ? 'Aucune des trois couches n’a été trouvée. Cela ne prouve pas que l’image est authentique.'
        : 'None of the three layers was found. This does not prove the image is authentic.'
      : fr()
        ? `${v.signals} couche${v.signals > 1 ? 's' : ''} sur 3 signale${v.signals > 1 ? 'nt' : ''} une intervention de l’IA.`
        : `${v.signals} of 3 layers report AI involvement.`;

  const m = v.c2pa.active;
  const c2paStatus = !v.c2pa.present ? 'none' : m?.valid ? 'found' : 'bad';
  const c2paChip = !v.c2pa.present ? t('r.absent', 'Not found') : m?.valid ? t('r.valid', 'Valid') : t('r.invalid', 'Invalid');
  const trust =
    m?.signature.trusted === true ? t('r.trusted', 'trusted signer') : fr() ? 'signataire non vérifié (hors liste de confiance)' : 'signer not on a trust list';

  const c2paBody = m
    ? `<dl class="kv">
        <dt>${fr() ? 'Signé par' : 'Signed by'}</dt><dd>${esc(m.signature.subject)} <span class="muted small">· ${esc(trust)}</span></dd>
        <dt>${fr() ? 'Émetteur' : 'Issuer'}</dt><dd>${esc(m.signature.issuer)}</dd>
        <dt>${fr() ? 'Validité' : 'Valid'}</dt><dd>${date(m.signature.notBefore)} → ${date(m.signature.notAfter)}</dd>
        <dt>${fr() ? 'Outil' : 'Generator'}</dt><dd>${esc(m.claimGenerator ?? '—')}</dd>
        ${m.actions.map((a) => `<dt>${actionLabel(a.action)}</dt><dd>${sourceLabel(a.digitalSourceType)}${a.softwareAgent ? ` · ${esc(a.softwareAgent)}` : ''}</dd>`).join('')}
      </dl>
      <ul class="checks">${m.validation.map((c) => `<li class="${c.ok ? '' : 'fail'}" title="${esc(c.code)}">${checkLabel(c.code, c.message)}</li>`).join('')}</ul>`
    : `<p class="muted small">${esc(v.c2pa.error ?? (fr() ? 'Aucun manifeste C2PA dans ce fichier.' : 'No C2PA manifest in this file.'))}</p>`;

  const md = v.metadata;
  const mdBody = md.digitalSourceType
    ? `<dl class="kv"><dt>${fr() ? 'Origine' : 'Source'}</dt><dd>${sourceLabel(md.digitalSourceType)}</dd>${md.aiSystem ? `<dt>${fr() ? 'Système d’IA' : 'AI system'}</dt><dd>${esc(md.aiSystem)}</dd>` : ''}</dl>`
    : `<p class="muted small">${fr() ? 'Pas de champ IPTC « Digital Source Type ».' : 'No IPTC “Digital Source Type” field.'}</p>`;

  const wm = v.watermark;
  const wmBody = wm.detected
    ? `<dl class="kv"><dt>${fr() ? 'Type' : 'Type'}</dt><dd>${wm.payload?.aiModified ? sourceLabel('compositeWithTrainedAlgorithmicMedia') : sourceLabel('trainedAlgorithmicMedia')}</dd>
       <dt>ID</dt><dd><code>${wm.payload!.id.toString(16).padStart(8, '0')}</code></dd>
       <dt>${fr() ? 'Confiance' : 'Confidence'}</dt><dd>${Math.round(wm.confidence * 100)} %</dd></dl>
       <div class="meter" aria-hidden="true"><i style="width:${Math.round(wm.confidence * 100)}%"></i></div>`
    : `<p class="muted small">${fr() ? 'Aucun filigrane Filigrane détecté dans les pixels.' : 'No Filigrane watermark detected in the pixels.'}</p>`;

  const card = (title: string, status: string, chip: string, body: string) =>
    `<article class="card layer-card"><h4>${title}<span class="status ${status}">${chip}</span></h4>${body}</article>`;

  return `
<div class="verdict ${verdictClass}" role="status">
  ${previewUrl ? `<img src="${previewUrl}" alt="" />` : ''}
  <div>
    <div class="big">${esc(verdictText)}</div>
    <div class="small">${esc(sub)}</div>
    ${v.tampered ? `<div class="small" style="color:var(--bad);font-weight:600">${fr() ? 'Le fichier a été modifié après la signature du manifeste.' : 'The file was modified after the manifest was signed.'}</div>` : ''}
    ${v.width ? `<div class="small muted">${v.width} × ${v.height} px · ${esc(v.mimeType ?? '')}</div>` : ''}
  </div>
</div>
${card(fr() ? '1 · Manifeste C2PA signé' : '1 · Signed C2PA manifest', c2paStatus, c2paChip, c2paBody)}
${card(fr() ? '2 · Métadonnées IPTC' : '2 · IPTC metadata', md.ai ? 'found' : 'none', md.ai ? t('r.found', 'Found') : t('r.absent', 'Not found'), mdBody)}
${card(fr() ? '3 · Filigrane invisible' : '3 · Invisible watermark', wm.detected ? 'found' : 'none', wm.detected ? t('r.found', 'Found') : t('r.absent', 'Not found'), wmBody)}`;
}
